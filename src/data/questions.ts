export function getQuiz(quizId: string): Quiz {
  return QUIZZES.find((quiz) => quiz.id === quizId) ?? QUIZZES[0];
}

export function isDifficulty(value: string | undefined): value is Difficulty {
  return value === 'easy' || value === 'medium' || value === 'hard';
}

export function shuffle<T>(items: T[]): T[] {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index--) {
    const swap = Math.floor(Math.random() * (index + 1));
    [copy[index], copy[swap]] = [copy[swap], copy[index]];
  }
  return copy;
}

export function buildQuiz(quizId: string, difficulty: Difficulty, count = QUIZ_LENGTH): Question[] {
  const { categoryId } = getQuiz(quizId);
  const matching = BANK.filter(
    (question) => question.categoryId === categoryId && question.difficulty === difficulty
  );
  const inCategory = BANK.filter((question) => question.categoryId === categoryId);

  const pool = matching.length >= count ? matching : inCategory;
  return shuffle(pool).slice(0, count);
}

export function countFor(quizId: string, difficulty: Difficulty) {
  const { categoryId } = getQuiz(quizId);
  return BANK.filter(
    (question) => question.categoryId === categoryId && question.difficulty === difficulty
  ).length;
}